// Part of ../../PROJECT.md — generate the immutable Worker reference bundle.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const appRoot = fileURLToPath(new URL("..", import.meta.url));
const projectRoot = fileURLToPath(new URL("../..", import.meta.url));
const outputUrl = new URL("../lib/generated/manual-engine-reference.ts", import.meta.url);
const validatorOutputUrl = new URL("../lib/generated/diagnostic-validator.cjs", import.meta.url);

const sources = {
  diagnosticSchema: "DIAGNOSTIC_OUTPUT_SCHEMA.json",
  taxonomyText: "DIAGNOSTIC_TAXONOMY.md",
  paperRulesText: "PAPER_RULES.md",
  creditLedgerText: "CREDIT_LEDGER.md",
  safeguardsText: "DIAGNOSTIC_SAFEGUARDS.md",
  uncertaintyText: "UNCERTAINTY_POLICY.md",
  promptText: "MANUAL_CODEX_DIAGNOSTIC_PROMPT.md",
  engineConfig: "prototype/engine_config.json",
  ledgerConfig: "prototype/credit_ledger_config.json",
  afmPaperRules: "prototype/paper_rules/afm_v0.2.json",
  sbrPaperRules: "prototype/paper_rules/sbr_v0.2.json",
};

const values = {};
for (const [key, relativePath] of Object.entries(sources)) {
  const text = await readFile(`${projectRoot}/${relativePath}`, "utf8");
  values[key] = relativePath.endsWith(".json") ? JSON.parse(text) : text;
}

const generated = `// Generated by scripts/sync-manual-engine-reference.mjs. Do not edit.\n` +
  `// Part of ../../../PROJECT.md — frozen v0.2 references bundled for the Worker.\n` +
  Object.entries(values).map(([key, value]) =>
    `export const ${key} = JSON.parse(${JSON.stringify(JSON.stringify(value))}) as unknown;\n`
  ).join("") +
  `export const sourceManifest = ${JSON.stringify(sources, null, 2)} as const;\n`;

const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
addFormats(ajv);
const validator = ajv.compile(values.diagnosticSchema);
const generatedValidator = `// Generated by scripts/sync-manual-engine-reference.mjs. Do not edit.\n` +
  `/* eslint-disable */\n` + standaloneCode(ajv, validator) + "\n";

if (process.argv.includes("--check")) {
  const current = await readFile(outputUrl, "utf8").catch(() => "");
  const currentValidator = await readFile(validatorOutputUrl, "utf8").catch(() => "");
  if (current !== generated || currentValidator !== generatedValidator) {
    throw new Error(`Worker reference bundle is stale. Run npm run reference:sync from ${appRoot}.`);
  }
  process.stdout.write("Worker reference bundle matches the Python reference sources.\n");
} else {
  await writeFile(outputUrl, generated, "utf8");
  await writeFile(validatorOutputUrl, generatedValidator, "utf8");
  process.stdout.write("Updated the Worker reference bundle and standalone diagnostic validator.\n");
}
